const I18nContext = createContext({
  lang: 'en',
  setLang: () => {},
  t: (key) => TRANSLATIONS.en[key] || ONBOARDING_TRANSLATIONS.en[key] || key
});

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    try {
      const saved = localStorage.getItem('reverse_ai_lang');
      return saved && TRANSLATIONS[saved] ? saved : 'en';
    } catch {
      return 'en';
    }
  });

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = (code) => {
    if (!TRANSLATIONS[code]) return;
    setLangState(code);
    try {
      localStorage.setItem('reverse_ai_lang', code);
    } catch {
      // ignore storage errors
    }
  };

  const t = (key) => {
    return (
      (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) ||
      (ONBOARDING_TRANSLATIONS[lang] && ONBOARDING_TRANSLATIONS[lang][key]) ||
      TRANSLATIONS.en[key] ||
      ONBOARDING_TRANSLATIONS.en[key] ||
      key
    );
  };

  return (
    <I18nContext.Provider value={{ lang, setLang, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}
